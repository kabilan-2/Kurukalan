-- Private application schema; do not add it to Supabase's exposed Data API schemas.
CREATE SCHEMA IF NOT EXISTS kurukalan;
REVOKE ALL ON SCHEMA kurukalan FROM PUBLIC;
SET search_path TO kurukalan;
CREATE TABLE IF NOT EXISTS users (
 id SERIAL PRIMARY KEY, name TEXT NOT NULL, mobile TEXT UNIQUE, email TEXT UNIQUE,
 lang TEXT NOT NULL DEFAULT 'en', created_at TEXT NOT NULL, last_login TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, role TEXT NOT NULL,
 user_id INTEGER REFERENCES users(id) ON DELETE CASCADE, expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS centers (
 id SERIAL PRIMARY KEY, name TEXT NOT NULL, name_ta TEXT NOT NULL DEFAULT '',
 district TEXT NOT NULL, person TEXT NOT NULL, phone TEXT NOT NULL,
 lat DOUBLE PRECISION NOT NULL, lng DOUBLE PRECISION NOT NULL, franchise INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS bookings (
 id SERIAL PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 name TEXT NOT NULL, mobile TEXT NOT NULL, email TEXT, address TEXT NOT NULL,
 photo BYTEA NOT NULL, photo_mime TEXT NOT NULL, unit TEXT NOT NULL, area DOUBLE PRECISION NOT NULL,
 kg INTEGER NOT NULL, containers INTEGER NOT NULL, container_kg INTEGER NOT NULL DEFAULT 2500,
 date TEXT NOT NULL, center_id INTEGER REFERENCES centers(id) ON DELETE SET NULL,
 status TEXT NOT NULL DEFAULT 'Pending', created_at TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS messages (
 id SERIAL PRIMARY KEY, name TEXT NOT NULL, mobile TEXT NOT NULL, text TEXT NOT NULL,
 created_at TEXT NOT NULL, email_delivery TEXT NOT NULL DEFAULT 'not_configured'
);
CREATE TABLE IF NOT EXISTS email_otp_challenges (
 email TEXT PRIMARY KEY, nonce TEXT NOT NULL, code_hash TEXT NOT NULL,
 expires_at BIGINT NOT NULL, attempts INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS app_metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS idx_bookings_user ON bookings(user_id);
REVOKE ALL ON ALL TABLES IN SCHEMA kurukalan FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA kurukalan FROM PUBLIC;
